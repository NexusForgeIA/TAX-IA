const C = require("./calculos.js"); const assert = require("assert");
assert.strictEqual(C.importeCarrera({ bajada: 2, porKm: 1, porMinuto: 0.5, minimo: 5, suplemento: 0 }, 1, 1), 5);
assert.strictEqual(C.importeCarrera({ bajada: "2,5", porKm: "1,2", porMinuto: 0, minimo: 0, suplemento: 1 }, 10, 0), 15.5);
const b = C.beneficioTurno({ recaudacion: 200, combustible: 40, peajes: 5, otros: 5, alquiler: 50, km: 100, horas: 10 });
assert.deepStrictEqual([b.gastos, b.neto, b.porKm, b.porHora], [100, 100, 1, 10]);
assert.strictEqual(C.beneficioTurno({ recaudacion: 10 }).porKm, null);
assert.deepStrictEqual(C.reparto({ recaudacion: 200, gastos: 40, porcentaje: 40, base: "neto" }), { base: 160, asalariado: 64, titular: 96 });
assert.deepStrictEqual(C.reparto({ recaudacion: 200, gastos: 40, porcentaje: 50, base: "recaudacion" }), { base: 200, asalariado: 100, titular: 60 });
assert.deepStrictEqual(C.objetivo({ objetivoMes: 3000, dias: 20, importeMedio: 12 }), { porDia: 150, carrerasDia: 13 });
assert.strictEqual(C.sumarMeses("2026-01-31", 1), "2026-02-28");
assert.strictEqual(C.sumarMeses("2026-10-20", 12), "2027-10-20");
assert.strictEqual(C.diasHasta("2026-10-30", "2026-10-20"), 10);
assert.strictEqual(C.estadoVencimiento({ fecha: "2026-10-10" }, "2026-10-20").estado, "vencido");
assert.strictEqual(C.estadoVencimiento({ fecha: "2026-11-01", aviso: 30 }, "2026-10-20").estado, "pronto");
assert.strictEqual(C.estadoVencimiento({ fecha: "2027-01-01" }, "2026-10-20").estado, "ok");
assert.strictEqual(C.estadoVencimiento({ ultima: "2025-11-01", cadaMeses: 12 }, "2026-10-20").fecha, "2026-11-01");
assert.strictEqual(C.estadoVencimiento({}, "2026-10-20").estado, "sin");
const r = C.resumen([{ importe: 10, km: 4, metodo: "efectivo" }, { importe: "5,5", km: 2, metodo: "tarjeta" }]);
assert.deepStrictEqual([r.n, r.total, r.km, r.medio, r.porMetodo.efectivo], [2, 15.5, 6, 7.75, 10]);
assert.strictEqual(C.inicioSemana("2026-10-20"), "2026-10-19");
assert.strictEqual(C.inicioMes("2026-10-20"), "2026-10-01");
assert.ok(C.csv([{ fecha: "2026-10-20", hora: "10:00", importe: 12.5, metodo: "efectivo", km: 3, origen: "A;B", destino: "", nota: "" }]).includes("12,5;efectivo;3;\"A;B\""));
console.log("calculos: ok");
